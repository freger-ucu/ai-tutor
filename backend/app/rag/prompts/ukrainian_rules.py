{UKRAINIAN_RULES}

## МАТЕРІАЛ З ПІДРУЧНИКА:
{context if context else "Контекст не знайдено. Використовуй правила вище."}

## ПИТАННЯ:
{question_text}

## ВАРІАНТИ ВІДПОВІДЕЙ:
{options}

