# Comprehensive Ukrainian rules embedded in prompt
UKRAINIAN_RULES = """
## ПУНКТУАЦІЯ

### Кома:
- Ставиться перед сполучниками **а, але, проте, однак, та** (у значенні 'але')
- Звертання виділяється комами з **ОБОХ боків**: "Сину, йди сюди"
- У складному реченні кома ставиться між частинами
- **НЕ ставиться** перед одиничним сполучником **і** в простому реченні з однорідними членами
- Ставиться перед повторюваними сполучниками: "і..., і..., і..."
- Ставиться для відокремлення вставних слів: "звичайно, напевно, по-перше"

### Тире:
- Між підметом і присудком, якщо **обидва виражені іменником** у Н.в.: "Київ — столиця"
- У неповному реченні замість пропущеного члена
- Перед узагальнюючим словом ПІСЛЯ однорідних членів
- Між цифрами для позначення проміжку: "10—15 років"

### Двокрапка:
- Після узагальнюючого слова ПЕРЕД однорідними членами
- Перед прямою мовою після слів автора
- У безсполучниковому реченні (причина, пояснення)

### Крапка з комою:
- Між поширеними частинами складного речення
- Між частинами, далекими за змістом

## СИНТАКСИС

### Типи речень:
- **Складносурядне**: рівноправні частини + сполучники (і, а, але, чи, або, однак)
- **Складнопідрядне**: головна + залежна частина + підрядні сполучники (що, щоб, який, коли, бо)
- **Безсполучникове**: частини без сполучників

### Односкладні речення:
- **Називне**: головний член у **називному відмінку** (Н.в. - хто? що?). Приклад: "Вечір. Холодний день."
- **Означено-особове**: дієслово 1-2 особи (роблю, робиш, робимо)
- **Неозначено-особове**: дієслово 3 особи множини (говорять, кажуть)
- **Безособове**: немає підмета, безособове дієслово або слово стану (світає, холодно, треба)
- **Інфінітивне**: головний член - інфінітив (Мовчати!)

### Члени речення:
- **Підмет**: хто? що? (Н.в.)
- **Присудок**: що робить? що робив? який?
- **Додаток**: кого? чого? кому? що? ким? чим? на кому/чому? (непрямі відмінки)
- **Означення**: який? яка? яке? чий? котрий?
- **Обставина**: де? куди? коли? як? чому? навіщо?

### Словосполучення:
- **НЕ є словосполученням**: підмет+присудок, прийменник+іменник

## МОРФОЛОГІЯ

### Суфікси прикметників:
- **-СЬК-/-ЦЬК-**: від географічних назв, національностей (київський, німецький)
- **-ОВ-/-ЕВ-**: від іменників (вишневий, грушевий)
- **-Н-**: від дієслів (написаний, зроблений)

### Частини мови:
- Іменник: хто? що?
- Прикметник: який? яка? яке?
- Дієслово: що робити? що зробити?
- Прислівник: як? де? коли?
"""


def get_ukrainian_mega_prompt(
    grade: int,
    question_text: str,
    options: str,
    context: str,
    question_type: str = "general"
) -> str:
    """
    Generate MEGA-PROMPT for Ukrainian language questions.

    Combines rules + context + structured analysis in ONE prompt.
    """
