"""
Algebra rules and mega-prompt for Agentic RAG.
"""

ALGEBRA_RULES = """
## КВАДРАТНІ РІВНЯННЯ

- **Дискримінант**: D = b² - 4ac
- **Корені (D > 0)**: x₁,₂ = (-b ± √D) / (2a)
- **Корінь (D = 0)**: x = -b / (2a)
- **D < 0**: Немає дійсних коренів
- **Теорема Вієта**: x₁ + x₂ = -b/a, x₁ · x₂ = c/a

## ПРОГРЕСІЇ

### Арифметична прогресія:
- **n-й член**: aₙ = a₁ + d(n-1)
- **Різниця**: d = a₂ - a₁ = aₙ - aₙ₋₁
- **Сума**: Sₙ = n(a₁ + aₙ)/2 = n(2a₁ + d(n-1))/2

### Геометрична прогресія:
- **n-й член**: bₙ = b₁ · qⁿ⁻¹
- **Знаменник**: q = b₂/b₁ = bₙ/bₙ₋₁
- **Сума (q ≠ 1)**: Sₙ = b₁·(1 - qⁿ)/(1 - q) = b₁·(qⁿ - 1)/(q - 1)

## ФУНКЦІЇ

### Парабола y = ax² + bx + c:
- **a > 0**: гілки вгору ∪ (мінімум у вершині)
- **a < 0**: гілки вниз ∩ (максимум у вершині)
- **Вершина**: x₀ = -b/(2a)
- **Нулі**: розв'яжи ax² + bx + c = 0

### Область визначення:
- Дріб: знаменник ≠ 0
- Корінь парного степеня: підкореневий вираз ≥ 0
- Логарифм: аргумент > 0

## СТЕПЕНІ ТА КОРЕНІ

- √(a²) = |a| (модуль!)
- √(a·b) = √a · √b (a,b ≥ 0)
- √(k²·m) = k·√m (k > 0)
- aᵐ · aⁿ = aᵐ⁺ⁿ
- aᵐ / aⁿ = aᵐ⁻ⁿ
- (aᵐ)ⁿ = aᵐⁿ

## НЕРІВНОСТІ

- (вираз)² ≥ 0 завжди
- |вираз| ≥ 0 завжди
- ax² + bx + c > 0 при a > 0, D < 0: виконується для всіх x
- ax² + bx + c < 0 при a > 0, D < 0: не має розв'язків
"""


def get_algebra_mega_prompt(
    grade: int,
    question_text: str,
    options: str,
    context: str,
    question_type: str = "general"
) -> str:
    """
    Generate MEGA-PROMPT for Algebra questions.

    Emphasis on step-by-step calculations.
    """
    return f"""Ти експертний математик-репетитор для {grade} класу.

{ALGEBRA_RULES}

## МАТЕРІАЛ З ПІДРУЧНИКА:
{context if context else "Контекст не знайдено. Використовуй формули вище."}

## ПИТАННЯ:
{question_text}

## ВАРІАНТИ ВІДПОВІДЕЙ:
{options}

Відповідай ТІЛЬКИ буквою: A, B, C або D.
"""
