"""
History methodology and mega-prompt for Agentic RAG.
"""

HISTORY_RULES = """
## МЕТОДИКА РОБОТИ З ІСТОРИЧНИМИ ПИТАННЯМИ

### Для питань про ДАТИ:
1. Виписати ВСІ дати з усіх варіантів
2. Розташувати в хронологічному порядку
3. "Що раніше?" → найменша дата
4. "Що пізніше?" → найбільша дата
5. Перевірити: чи подія могла статися тоді?

### Для ПРИЧИННО-НАСЛІДКОВИХ питань:
1. Визначити часові рамки події
2. ПРИЧИНА завжди ДО наслідку (хронологічна перевірка!)
3. Виключити анахронізми
4. Подія → причини (що призвело) → наслідки (що сталося після)

### Для питань про ДОКУМЕНТИ:
1. Визначити контекст: коли, де, хто підписав
2. Які умови/положення документа
3. Порівняти варіанти з фактами
4. Виключити те, що суперечить історії

### Для питань про ПЕРСОНАЛІЇ:
1. Визначити епоху та діяльність особи
2. Основні досягнення/події
3. З якими подіями пов'язана
4. Виключити анахронізми

### ЗАГАЛЬНІ ПРАВИЛА:
- Спирайся на ФАКТИ з підручника
- Перевіряй хронологію
- Виключай явно неможливі варіанти
- Якщо сумніваєшся - аналізуй контекст епохи
"""


def get_history_mega_prompt(
    grade: int,
    question_text: str,
    options: str,
    context: str,
    question_type: str = "general"
) -> str:
    """
    Generate MEGA-PROMPT for History questions.

    Emphasis on chronological reasoning and fact verification.
    """
    return f"""Ти експертний історик України та світу для {grade} класу.

{HISTORY_RULES}

## МАТЕРІАЛ З ПІДРУЧНИКА:
{context if context else "Контекст не знайдено. Використовуй загальні історичні знання."}

## ПИТАННЯ:
{question_text}

## ВАРІАНТИ ВІДПОВІДЕЙ:
{options}

Відповідай ТІЛЬКИ буквою: A, B, C або D.
"""
